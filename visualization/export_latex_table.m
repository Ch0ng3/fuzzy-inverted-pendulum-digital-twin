function export_latex_table()
%EXPORT_LATEX_TABLE Write outputs/results/comparison_table.tex from comparison.csv,
%   so that the LaTeX report always shows the latest simulation results.
root = init_project();
T = readtable(fullfile(root, 'outputs', 'results', 'comparison.csv'), 'TextType', 'string');
fid = fopen(fullfile(root, 'outputs', 'results', 'comparison_table.tex'), 'w');
fprintf(fid, '%% generated by visualization/export_latex_table.m -- do not edit by hand\n');
fprintf(fid, '\\begin{tabular}{llcccccccc}\n\\toprule\n');
fprintf(fid, ['Scenario & Controller & $t_\\mathrm{catch}$ [s] & Balanced & $\\max|\\theta|$ [$^\\circ$] & ' ...
    'RMS $\\theta$ [$^\\circ$] & RMS $x$ [cm] & $t_s$ [s] & $\\int F^2$ [N$^2$s] & $\\max|F|$ [N]\\\\\n\\midrule\n']);
prev = "";
for i = 1:height(T)
    sc = T.scenario(i);
    if sc ~= prev && i > 1, fprintf(fid, '\\midrule\n'); end
    if sc ~= prev, scTxt = sc; else, scTxt = ""; end
    prev = sc;
    bal = "no"; if T.balanced(i), bal = "yes"; end
    fprintf(fid, '%s & %s & %.2f & %s & %.1f & %.2f & %.1f & %.2f & %.1f & %.1f\\\\\n', ...
        scTxt, upperFirst(T.controller(i)), T.t_catch_s(i), bal, T.max_theta_deg(i), T.rms_theta_deg(i), ...
        T.rms_x_cm(i), T.settle_s(i), T.effort_N2s(i), T.max_F_N(i));
end
fprintf(fid, '\\bottomrule\n\\end{tabular}\n');
fclose(fid);
fprintf('LaTeX table written: outputs/results/comparison_table.tex\n');
end

function s = upperFirst(s)
s = upper(extractBefore(s, 2)) + extractAfter(s, 1);
end
